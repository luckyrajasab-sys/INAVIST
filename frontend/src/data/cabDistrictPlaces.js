export const getDistrictById = (districtId) => {
  return CAB_DISTRICT_HUBS.find((d) => d.id === districtId) || CAB_DISTRICT_HUBS[0];
};

export const searchDistricts = (query) => {
  if (!query || query.trim() === "") return CAB_DISTRICT_HUBS;
  const q = query.toLowerCase();
  return CAB_DISTRICT_HUBS.filter(
    (d) =>
      d.districtName.toLowerCase().includes(q) ||
      d.state.toLowerCase().includes(q) ||
      d.id.toLowerCase().includes(q)
  );
};
