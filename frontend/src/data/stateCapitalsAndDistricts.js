export const getCapitalForState = (stateName) => {
  if (!stateName) return null;
  const match = ALL_INDIAN_STATES_DIRECTORY.find(
    (s) => s.state.toLowerCase() === stateName.trim().toLowerCase()
  );
  return match || null;
};

export const getAllDistrictsForState = (stateName) => {
  const stateData = getCapitalForState(stateName);
  return stateData ? stateData.keyDistricts : [];
};

export const getAllStatesWithDistricts = () => {
  return ALL_INDIAN_STATES_DIRECTORY.map(s => ({
    state: s.state,
    capital: s.capital,
    totalDistricts: s.keyDistricts.length,
    districts: s.keyDistricts
  }));
};

export const getAllIndianDistricts = () => {
  const list = [];
  ALL_INDIAN_STATES_DIRECTORY.forEach((s) => {
    s.keyDistricts.forEach((dist) => {
      const cleanName = dist.split("(")[0].trim();
      list.push({
        district: cleanName,
        displayName: dist,
        state: s.state,
        capital: s.capital
      });
    });
  });
  return list;
};

